import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { copyFileSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';

test('forwards NAPI options and locked Cargo arguments through Yarn', t => {
  const root = mkdtempSync(join(tmpdir(), 'typst-node-build-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  mkdirSync(join(root, 'scripts'));
  copyFileSync(join(import.meta.dirname, 'build.mjs'), join(root, 'scripts', 'build.mjs'));
  writeFileSync(
    join(root, 'package.json'),
    JSON.stringify({
      private: true,
      scripts: {
        napi: 'node capture.mjs',
        tsc: 'node -e "process.exit(0)"',
      },
    }),
  );
  writeFileSync(
    join(root, 'capture.mjs'),
    "console.log('NAPI_ARGS:' + JSON.stringify(process.argv.slice(2)));",
  );
  const result = spawnSync(
    process.execPath,
    [join(root, 'scripts', 'build.mjs'), '--release', '--target', 'x86_64-unknown-linux-gnu'],
    { cwd: root, encoding: 'utf8' },
  );
  assert.equal(result.status, 0, result.stderr);
  const line = result.stdout.split('\n').find(value => value.startsWith('NAPI_ARGS:'));
  assert.ok(line, result.stdout);
  assert.deepEqual(JSON.parse(line.slice('NAPI_ARGS:'.length)), [
    'build',
    '--platform',
    '--dts-header',
    "/* auto-generated by NAPI-RS */ /* eslint-disable */ import type * as types from './index.js';",
    '--dts',
    'index-napi.d.ts',
    '--js',
    'index-napi.js',
    '--pipe',
    'prettier -w',
    '--release',
    '--target',
    'x86_64-unknown-linux-gnu',
    '--',
    '--locked',
  ]);
});
